const settingKeyDesktopReleaseStorage = "desktop_release_storage_v1"
const DesktopReleaseUploadExpiry = 15 * time.Minute
const DesktopReleaseImmutableCacheControl = "public, max-age=31536000, immutable"
const DesktopReleaseStableCacheControl = "no-cache, max-age=0, must-revalidate"
const desktopReleaseMaxBytes int64 = 4 << 30

var (
	ErrDesktopReleaseStorageInvalid     = infraerrors.BadRequest("DESKTOP_RELEASE_STORAGE_INVALID", "invalid desktop release storage request or configuration")
	ErrDesktopReleaseStorageUnavailable = infraerrors.New(http.StatusServiceUnavailable, "DESKTOP_RELEASE_STORAGE_UNAVAILABLE", "desktop release storage is unavailable; configure a separate bucket and backup S3 credentials")
	ErrDesktopReleaseStorageTestFailed  = infraerrors.BadRequest("DESKTOP_RELEASE_STORAGE_TEST_FAILED", "desktop release storage test failed; verify bucket permissions and the public domain mapping")
	desktopReleaseBucketPattern         = regexp.MustCompile(`^[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]$`)
	desktopReleaseVersionPattern        = regexp.MustCompile(`^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$`)
	desktopReleaseAssetPattern          = regexp.MustCompile(`^milocode/releases/((?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*))/(win32-x64|darwin-arm64)/([A-Za-z0-9][A-Za-z0-9._-]*)$`)
	desktopReleaseSHA256Pattern         = regexp.MustCompile(`^[a-f0-9]{64}$`)
	desktopReleaseETagPattern           = regexp.MustCompile(`^"[A-Za-z0-9._:-]{1,128}"$`)
)

// DesktopReleaseStorageConfig stores only the independent destination. Credentials
// are resolved from the backup service for each publishing request, never copied.
type DesktopReleaseStorageConfig struct {
	Bucket        string `json:"bucket"`
	PublicBaseURL string `json:"public_base_url"`
}

type DesktopReleaseStorageView struct {
	DesktopReleaseStorageConfig
	ReleaseBaseURL     string `json:"release_base_url"`
	BackupS3Configured bool   `json:"backup_s3_configured"`
	Configured         bool   `json:"configured"`
}

type DesktopReleaseUploadRequest struct {
	Key         string `json:"key"`
	Size        int64  `json:"size"`
	ContentType string `json:"content_type"`
	SHA256      string `json:"sha256"`
	SHA512      string `json:"sha512"`
	Version     string `json:"version"`
	IfNoneMatch string `json:"if_none_match,omitempty"`
	IfMatch     string `json:"if_match,omitempty"`
}

type DesktopReleaseUpload struct {
	URL       string            `json:"url"`
	Headers   map[string]string `json:"headers"`
	ExpiresAt time.Time         `json:"expires_at"`
}

type DesktopReleaseObjectHead struct {
	Exists  bool   `json:"exists"`
	Size    int64  `json:"size,omitempty"`
	SHA512  string `json:"sha512,omitempty"`
	Version string `json:"version,omitempty"`
	ETag    string `json:"etag,omitempty"`
}

// DesktopReleaseObjectStore exposes narrowly scoped publishing operations. Probe
// bodies are small generated bytes, never uploaded installer bodies.
type DesktopReleaseObjectStore interface {
	Head(context.Context, string) (*DesktopReleaseObjectHead, error)
	PresignUpload(context.Context, DesktopReleaseUploadRequest, string, time.Duration) (*DesktopReleaseUpload, error)
	PutProbe(context.Context, string, []byte) error
	GetProbe(context.Context, string) ([]byte, error)
	DeleteProbe(context.Context, string) error
}
type DesktopReleaseObjectStoreFactory func(context.Context, *BackupS3Config) (DesktopReleaseObjectStore, error)

type DesktopReleaseStorageService struct {
	repo    SettingRepository
	backup  *BackupService
	factory DesktopReleaseObjectStoreFactory
	// Tests replace only the external HTTP boundary; production always uses the
	// shared SSRF-validating client with redirects disabled below.
	publicProbe  func(context.Context, string, []byte) error
	downloads    desktopDownloadCache
	downloadFeed func(context.Context, string) ([]byte, error)
}

func NewDesktopReleaseStorageService(repo SettingRepository, backup *BackupService, factory DesktopReleaseObjectStoreFactory) *DesktopReleaseStorageService {
	return &DesktopReleaseStorageService{repo: repo, backup: backup, factory: factory, publicProbe: probeDesktopReleasePublicObject, downloadFeed: fetchDesktopDownloadFeed}
}

func normalizeDesktopReleaseStorage(in DesktopReleaseStorageConfig) (DesktopReleaseStorageConfig, error) {
	in.Bucket = strings.TrimSpace(in.Bucket)
	in.PublicBaseURL = strings.TrimSpace(in.PublicBaseURL)
	if in.Bucket == "" && in.PublicBaseURL == "" {
		return in, nil
	}
	if !desktopReleaseBucketPattern.MatchString(in.Bucket) || strings.Contains(in.Bucket, "..") || strings.Contains(in.Bucket, ".-") || strings.Contains(in.Bucket, "-.") {
		return in, ErrDesktopReleaseStorageInvalid
	}
	u, err := url.Parse(in.PublicBaseURL)
	if err != nil || u.Scheme != "https" || u.Host == "" || u.User != nil || u.Opaque != "" || u.RawQuery != "" || u.ForceQuery || u.Fragment != "" || strings.Contains(in.PublicBaseURL, "#") || u.RawPath != "" || (u.Path != "" && u.Path != "/") {
		return in, ErrDesktopReleaseStorageInvalid
	}
	normalized, err := urlvalidator.ValidateHTTPSURL(in.PublicBaseURL, urlvalidator.ValidationOptions{AllowPrivate: false})
	if err != nil {
		return in, ErrDesktopReleaseStorageInvalid
	}
	in.PublicBaseURL = strings.TrimRight(normalized, "/")
	return in, nil
}

func (s *DesktopReleaseStorageService) load(ctx context.Context) (DesktopReleaseStorageConfig, error) {
	var cfg DesktopReleaseStorageConfig
	if s == nil || s.repo == nil {
		return cfg, ErrDesktopReleaseStorageUnavailable
	}
	raw, err := s.repo.GetValue(ctx, settingKeyDesktopReleaseStorage)
	if errors.Is(err, ErrSettingNotFound) || (err == nil && strings.TrimSpace(raw) == "") {
		return cfg, nil
	}
	if err != nil {
		return cfg, ErrDesktopReleaseStorageUnavailable
	}
	decoder := json.NewDecoder(strings.NewReader(raw))
	decoder.DisallowUnknownFields()
	if decoder.Decode(&cfg) != nil {
		return cfg, ErrDesktopReleaseStorageUnavailable
	}
	if decoder.Decode(new(any)) != io.EOF {
		return cfg, ErrDesktopReleaseStorageUnavailable
	}
	return normalizeDesktopReleaseStorage(cfg)
}

func (s *DesktopReleaseStorageService) backupConfig(ctx context.Context) (*BackupS3Config, error) {
	if s == nil || s.backup == nil {
		return nil, ErrDesktopReleaseStorageUnavailable
	}
	cfg, err := s.backup.loadS3Config(ctx)
	if err != nil || cfg == nil || !cfg.IsConfigured() {
		return nil, ErrDesktopReleaseStorageUnavailable
	}
	return cfg, nil
}

func desktopReleaseView(cfg DesktopReleaseStorageConfig, backup *BackupS3Config) *DesktopReleaseStorageView {
	view := &DesktopReleaseStorageView{DesktopReleaseStorageConfig: cfg, BackupS3Configured: backup != nil && backup.IsConfigured()}
	if cfg.PublicBaseURL != "" {
		view.ReleaseBaseURL = cfg.PublicBaseURL + "/milocode/"
	}
	view.Configured = cfg.Bucket != "" && cfg.PublicBaseURL != "" && view.BackupS3Configured && cfg.Bucket != backup.Bucket
	return view
}

func (s *DesktopReleaseStorageService) Get(ctx context.Context) (*DesktopReleaseStorageView, error) {
	cfg, err := s.load(ctx)
	if err != nil {
		return nil, err
	}
	backup, _ := s.backupConfig(ctx)
	return desktopReleaseView(cfg, backup), nil
}

func (s *DesktopReleaseStorageService) Update(ctx context.Context, in DesktopReleaseStorageConfig) (*DesktopReleaseStorageView, error) {
	cfg, err := normalizeDesktopReleaseStorage(in)
	if err != nil {
		return nil, err
	}
	backup, _ := s.backupConfig(ctx)
	if cfg.Bucket != "" {
		if backup == nil {
			return nil, ErrDesktopReleaseStorageUnavailable
		}
		if cfg.Bucket == backup.Bucket {
			return nil, ErrDesktopReleaseStorageInvalid
		}
	}
	if s == nil || s.repo == nil {
		return nil, ErrDesktopReleaseStorageUnavailable
	}
	raw, err := json.Marshal(cfg)
	if err != nil || s.repo.Set(ctx, settingKeyDesktopReleaseStorage, string(raw)) != nil {
		return nil, ErrDesktopReleaseStorageUnavailable
	}
	return desktopReleaseView(cfg, backup), nil
}

func (s *DesktopReleaseStorageService) resolveStore(ctx context.Context, cfg DesktopReleaseStorageConfig) (DesktopReleaseObjectStore, error) {
	backup, err := s.backupConfig(ctx)
	if err != nil {
		return nil, err
	}
	if cfg.Bucket == "" || cfg.PublicBaseURL == "" {
		return nil, ErrDesktopReleaseStorageUnavailable
	}
	if cfg.Bucket == backup.Bucket {
		return nil, ErrDesktopReleaseStorageInvalid
	}
	// Copy before overriding the destination. Never mutate the backup service's
	// config or feed the backup's cached store (which is bound to its own bucket).
	resolved := *backup
	resolved.Bucket, resolved.Prefix = cfg.Bucket, "milocode/"
	if s.factory == nil {
		return nil, ErrDesktopReleaseStorageUnavailable
	}
	store, err := s.factory(ctx, &resolved)
	if err != nil {
		return nil, ErrDesktopReleaseStorageUnavailable
	}
	return store, nil
}

func desktopReleaseKey(key string) (version, contentType, cacheControl string, err error) {
	if len(key) > 512 || key != strings.TrimSpace(key) || strings.Contains(key, "..") {
		return "", "", "", ErrDesktopReleaseStorageInvalid
	}
	switch key {
	case "milocode/stable/win32-x64/latest.json":
		return "", "application/json", DesktopReleaseStableCacheControl, nil
	case "milocode/stable/darwin-arm64/appcast.xml":
		return "", "application/xml", DesktopReleaseStableCacheControl, nil
	}
	parts := desktopReleaseAssetPattern.FindStringSubmatch(key)
	if parts == nil {
		return "", "", "", ErrDesktopReleaseStorageInvalid
	}
	name := parts[3]
	if parts[2] == "win32-x64" && (strings.HasSuffix(name, ".exe") || strings.HasSuffix(name, ".exe.blockmap")) {
		return parts[1], "application/octet-stream", DesktopReleaseImmutableCacheControl, nil
	}
	if parts[2] == "darwin-arm64" {
		if strings.HasSuffix(name, ".zip") {
			return parts[1], "application/zip", DesktopReleaseImmutableCacheControl, nil
		}
		if strings.HasSuffix(name, ".dmg") {
			return parts[1], "application/x-apple-diskimage", DesktopReleaseImmutableCacheControl, nil
		}
	}
	return "", "", "", ErrDesktopReleaseStorageInvalid
}

func validateDesktopReleaseUpload(in DesktopReleaseUploadRequest) (string, error) {
	pathVersion, mime, cache, err := desktopReleaseKey(in.Key)
	if err != nil || in.ContentType != mime || in.Size <= 0 || in.Size > desktopReleaseMaxBytes || len(in.Version) > 64 || !desktopReleaseVersionPattern.MatchString(in.Version) || !desktopReleaseSHA256Pattern.MatchString(in.SHA256) {
		return "", ErrDesktopReleaseStorageInvalid
	}
	hash, err := base64.StdEncoding.DecodeString(in.SHA512)
	if err != nil || len(hash) != 64 || base64.StdEncoding.EncodeToString(hash) != in.SHA512 {
		return "", ErrDesktopReleaseStorageInvalid
	}
	if pathVersion != "" {
		if pathVersion != in.Version || in.IfNoneMatch != "*" || in.IfMatch != "" {
			return "", ErrDesktopReleaseStorageInvalid
		}
	} else {
		if in.Size > 4<<20 {
			return "", ErrDesktopReleaseStorageInvalid
		}
		if !((in.IfNoneMatch == "*" && in.IfMatch == "") || (in.IfNoneMatch == "" && desktopReleaseETagPattern.MatchString(in.IfMatch))) {
			return "", ErrDesktopReleaseStorageInvalid
		}
	}
	return cache, nil
}

func (s *DesktopReleaseStorageService) Head(ctx context.Context, key string) (*DesktopReleaseObjectHead, error) {
	if _, _, _, err := desktopReleaseKey(key); err != nil {
		return nil, err
	}
	cfg, err := s.load(ctx)
	if err != nil {
		return nil, err
	}
	store, err := s.resolveStore(ctx, cfg)
	if err != nil {
		return nil, err
	}
	result, err := store.Head(ctx, key)
	if err != nil {
		return nil, ErrDesktopReleaseStorageUnavailable
	}
	return result, nil
}

func (s *DesktopReleaseStorageService) PresignUpload(ctx context.Context, in DesktopReleaseUploadRequest) (*DesktopReleaseUpload, error) {
	cache, err := validateDesktopReleaseUpload(in)
	if err != nil {
		return nil, err
	}
	cfg, err := s.load(ctx)
	if err != nil {
		return nil, err
	}
	store, err := s.resolveStore(ctx, cfg)
	if err != nil {
		return nil, err
	}
	result, err := store.PresignUpload(ctx, in, cache, DesktopReleaseUploadExpiry)
	if err != nil {
		return nil, ErrDesktopReleaseStorageUnavailable
	}
	return result, nil
}

func (s *DesktopReleaseStorageService) TestConnection(ctx context.Context, in DesktopReleaseStorageConfig) (resultErr error) {
	cfg, err := normalizeDesktopReleaseStorage(in)
	if err != nil {
		return err
	}
	ctx, cancel := context.WithTimeout(ctx, 25*time.Second)
	defer cancel()
	store, err := s.resolveStore(ctx, cfg)
	if err != nil {
		return err
	}
	key := "milocode/.probe/" + uuid.NewString() + ".txt"
	body := []byte("milocode-release-probe-" + uuid.NewString())
	// Even an ambiguous failed Put may have stored the object. Cleanup uses an
	// independent bounded context and never touches release objects.
	defer func() {
		cleanup, stop := context.WithTimeout(context.WithoutCancel(ctx), 5*time.Second)
		defer stop()
		if store.DeleteProbe(cleanup, key) != nil {
			resultErr = ErrDesktopReleaseStorageTestFailed
		}
	}()
	if store.PutProbe(ctx, key, body) != nil {
		return ErrDesktopReleaseStorageTestFailed
	}
	received, err := store.GetProbe(ctx, key)
	if err != nil || !bytes.Equal(body, received) {
		return ErrDesktopReleaseStorageTestFailed
	}
	if s.publicProbe == nil || s.publicProbe(ctx, cfg.PublicBaseURL+"/"+key, body) != nil {
		return ErrDesktopReleaseStorageTestFailed
	}
	return nil
}

func probeDesktopReleasePublicObject(ctx context.Context, rawURL string, expected []byte) error {
	validated, err := urlvalidator.ValidateHTTPSURL(rawURL, urlvalidator.ValidationOptions{AllowPrivate: false})
	if err != nil {
		return ErrDesktopReleaseStorageTestFailed
	}
	shared, err := httpclient.GetClient(httpclient.Options{Timeout: 10 * time.Second, ValidateResolvedIP: true})
	if err != nil {
		return ErrDesktopReleaseStorageTestFailed
	}
	return desktopReleaseProbeWithClient(ctx, validated, expected, shared)
}

func desktopReleaseProbeWithClient(ctx context.Context, validated string, expected []byte, shared *http.Client) error {
	client := *shared
	client.CheckRedirect = func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, validated, nil)
	if err != nil {
		return ErrDesktopReleaseStorageTestFailed
	}
	req.Header.Set("Cache-Control", "no-cache")
	resp, err := client.Do(req)
	if err != nil {
		return ErrDesktopReleaseStorageTestFailed
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		return ErrDesktopReleaseStorageTestFailed
	}
	got, err := io.ReadAll(io.LimitReader(resp.Body, 4097))
	if err != nil || !bytes.Equal(got, expected) {
		return ErrDesktopReleaseStorageTestFailed
	}
	return nil
}
